import { chromium } from "playwright-core";
import { readdirSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
const base = process.argv[2] ?? "http://localhost:3100";
const cache = join(homedir(), "Library", "Caches", "ms-playwright");
const builds = existsSync(cache) ? readdirSync(cache).filter((d) => /^chromium-\d+$/.test(d)).sort() : [];
const exe = builds.length ? join(cache, builds[builds.length - 1], "chrome-mac-arm64", "Google Chrome for Testing.app", "Contents", "MacOS", "Google Chrome for Testing") : undefined;
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror:", e.message));
await page.goto(`${base}/?lang=de`, { waitUntil: "domcontentloaded", timeout: 90_000 });
await page.getByRole("button", { name: /wetter/i }).waitFor({ timeout: 60_000 });
const rail = await page.locator("nav[aria-label='Themen'] .rail__item").allInnerTexts();
const label = await page.locator(".strip .metric .label").first().innerText();
const htmlLang = await page.evaluate(() => document.documentElement.lang);
console.log("de rail:", rail.slice(0, 5).join("/"), "| first figure:", label, "| html lang:", htmlLang);
await page.getByRole("button", { name: "FR", exact: true }).click();
await page.getByRole("button", { name: /météo/i }).waitFor({ timeout: 20_000 });
const frGroups = await page.locator("nav[aria-label='Thèmes'] .rail__group").allInnerTexts();
const stored = await page.evaluate(() => localStorage.getItem("swiss-now:lang"));
console.log("fr groups:", frGroups.join("/"), "| stored:", stored, "| ok:", stored === "fr" && frGroups.length === 3);
await page.goto(`${base}/?topic=politics&lang=it`, { waitUntil: "domcontentloaded" });
await page.locator(".legend--ramp .label").waitFor({ timeout: 60_000 });
const legend = await page.locator(".legend--ramp .label").innerText();
const modes = await page.locator("nav[aria-label='Vista'] .modes__item").allInnerTexts();
console.log("it legend:", legend, "| modes:", modes.join("/"), "| ok:", /quota di s/i.test(legend) && modes.length === 4);
await page.goto(`${base}/?topic=energy&mode=charts&lang=fr`, { waitUntil: "domcontentloaded" });
await page.locator(".charts__title").waitFor({ timeout: 60_000 });
console.log("fr charts title:", await page.locator(".charts__title").first().innerText());
await page.goto(`${base}/today?lang=it`, { waitUntil: "domcontentloaded" });
await page.locator(".chapter__headline").first().waitFor({ timeout: 60_000 });
console.log("it today:", await page.locator(".hud--top .label").first().innerText(), "|", await page.locator(".chapter__headline").first().innerText());
await browser.close();
